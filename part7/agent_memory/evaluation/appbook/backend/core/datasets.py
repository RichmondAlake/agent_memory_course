"""The evaluation data: public benchmarks pinned to a revision, and the sets the notebook generates by rule.

- LongMemEval-S (cleaned): HF xiaowu0162/longmemeval-cleaned @ 98d7416, MIT. Sampled per question type with a seed;
  each haystack trimmed to its evidence sessions plus distractors up to a token budget.
- MemoryAgentBench FactConsolidation (single-hop, 6k): HF ai-hyz/MemoryAgentBench @ 7ea0669, MIT.
- Generated by rule: the memory-operations scenario.
"""
from __future__ import annotations

import json
import random
import re
import threading
from functools import lru_cache
from pathlib import Path

import pandas as pd

SEED = 7
LME_REPO, LME_REVISION = "xiaowu0162/longmemeval-cleaned", "98d7416c24c778c2fee6e6f3006e7a073259d48f"
MAB_REPO, MAB_REVISION = "ai-hyz/MemoryAgentBench", "7ea066982b140a19337e17e60d45d4076e042faf"
_lme_lock = threading.Lock()
_encoder = None


def tokens(text: str) -> int:
    global _encoder
    if _encoder is None:
        import tiktoken

        _encoder = tiktoken.get_encoding("o200k_base")
    return len(_encoder.encode(str(text), disallowed_special=()))


# ── LongMemEval ───────────────────────────────────────────────────────────────────────────────────────────────
@lru_cache(maxsize=1)
def lme_index() -> tuple[str, list[dict]]:
    """The file's path and every question's id, type and byte offsets (only the sampled questions are decoded)."""
    from huggingface_hub import hf_hub_download

    with _lme_lock:
        path = hf_hub_download(LME_REPO, "longmemeval_s_cleaned.json", repo_type="dataset", revision=LME_REVISION)
    raw = Path(path).read_bytes()
    heads = list(re.finditer(rb'\n    \{\s*"question_id":\s*"([^"]+)",\s*"question_type":\s*"([^"]+)"', raw))
    index = [{"position": i, "question_id": h.group(1).decode(), "question_type": h.group(2).decode(), "start": h.start() + 1,
              "end": heads[i + 1].start() if i + 1 < len(heads) else raw.rindex(b"]")} for i, h in enumerate(heads)]
    return path, index


def _decode(path: str, entry: dict) -> dict:
    with open(path, "rb") as f:
        f.seek(entry["start"])
        return json.loads(f.read(entry["end"] - entry["start"]).rstrip().rstrip(b","))


def lme_sample(per_type: int, abstention: int, budget: int = 20000) -> list[dict]:
    """The notebook's sample: per_type answerable questions per type plus `abstention` unanswerable ones, seed 7,
    each haystack trimmed to every evidence session plus the question's own distractors up to `budget` tokens."""
    path, index = lme_index()
    rng = random.Random(SEED)
    types = sorted({q["question_type"] for q in index})
    chosen = [q for t in types for q in rng.sample([q for q in index if q["question_type"] == t
                                                    and not q["question_id"].endswith("_abs")], per_type)]
    chosen += rng.sample([q for q in index if q["question_id"].endswith("_abs")], abstention)
    sample = []
    for entry in chosen:
        q = _decode(path, entry)
        sessions = list(zip(q["haystack_session_ids"], q["haystack_dates"], q["haystack_sessions"]))
        evidence = set(q["answer_session_ids"])
        size = lambda turns: sum(tokens(t["content"]) for t in turns)
        keep = {s[0] for s in sessions if s[0] in evidence}
        used = sum(size(s[2]) for s in sessions if s[0] in evidence)
        for session_id, _, turns in random.Random(f"{SEED}-{q['question_id']}").sample(sessions, len(sessions)):
            if session_id not in keep and used + (n := size(turns)) <= budget:
                keep.add(session_id)
                used += n
        q["sessions"] = [s for s in sessions if s[0] in keep]
        q["history_tokens"] = used
        q["abstention"] = q["question_id"].endswith("_abs")
        q["category"] = "abstention" if q["abstention"] else q["question_type"]
        for key in ("haystack_sessions", "haystack_session_ids", "haystack_dates"):
            q.pop(key, None)
        sample.append(q)
    return sample


# ── MemoryAgentBench FactConsolidation ────────────────────────────────────────────────────────────────────────
@lru_cache(maxsize=1)
def fact_consolidation() -> tuple[list[tuple[int, str]], list[dict]]:
    """The 455 numbered facts of factconsolidation_sh_6k and its 100 questions (gold answers as lists)."""
    conflicts = pd.read_parquet(f"hf://datasets/{MAB_REPO}@{MAB_REVISION}/data/Conflict_Resolution-00000-of-00001.parquet")
    row = conflicts[conflicts.metadata.map(lambda m: m["source"]) == "factconsolidation_sh_6k"].iloc[0]
    facts = [(int(m.group(1)), m.group(2)) for line in row["context"].splitlines() if (m := re.match(r"^(\d+)\.\s+(.*)$", line))]
    return facts, [{"question": q, "answers": list(a)} for q, a in zip(row["questions"], row["answers"])]


def history_of(facts, answers):
    """The newest fact ending with a gold answer, and the older values it replaced (same wording up to the value)."""
    for number, text in sorted(facts, reverse=True):
        for answer in answers:
            if text.rstrip(".").lower().endswith(answer.lower()):
                prefix = text[: len(text.rstrip(".")) - len(answer)]
                older = [t[len(prefix):].rstrip(".") for n, t in facts if n < number and t.startswith(prefix) and len(prefix) > 12]
                return number, prefix, [o for o in older if o.lower() != answer.lower()]
    return None, None, []


def fc_sample(n_questions: int, max_fact: int | None = None) -> tuple[list[tuple[int, str]], list[dict]]:
    """Facts to tell (all, or the first `max_fact`) and a seeded sample of questions those facts answer."""
    facts, questions = fact_consolidation()
    facts = [f for f in facts if max_fact is None or f[0] < max_fact]
    pool = []
    for q in questions:
        number, prefix, stale = history_of(facts, q["answers"])
        if number is not None:
            pool.append({**q, "fact_number": number, "prefix": prefix, "stale": stale})
    return facts, random.Random(SEED).sample(pool, min(n_questions, len(pool)))


def fc_messages(facts, chunk: int = 8) -> list[str]:
    """Eight facts per message keeps each one under MemoRizz's 600-character recall cap."""
    return [("Please remember these facts (a higher number wins):\n" + "\n".join(f"{n}. {t}" for n, t in facts[i:i + chunk]))
            for i in range(0, len(facts), chunk)]


# ── the memory-operations scenario ────────────────────────────────────────────────────────────────────────────
def scenario(seed) -> dict:
    """The conversation, the gold facts, the distractors, the updates and the canaries: all from one seed."""
    r = random.Random(seed)
    city, city2, other_city = r.sample(["Porto", "Lisbon", "Madrid", "Valencia", "Lyon", "Turin", "Ghent", "Bergen"], 3)
    service, other_service = r.sample(["retrieval-api", "embedding-worker", "docs-search", "rerank-gateway"], 2)
    manager, manager2, contact = r.sample(["Marco", "Yuki", "Omar", "Grace", "Priya", "Tomas"], 3)
    language = r.choice(["Python", "SQL", "TypeScript", "Go"])
    rotation = r.choice(["one week", "two weeks", "ten days"])
    window, window2 = r.sample(["Tuesday 02:00-04:00 UTC", "Thursday 01:00-03:00 UTC", "Sunday 22:00-23:59 UTC"], 2)
    turns = [
        ("fact", f"Hi, I'm Ada. I live in {city} and I own the {service} service."),
        ("fact", f"My manager is {manager}, and I prefer answers with {language} examples."),
        ("distractor", f"My friend keeps asking whether I'd ever move to {other_city}. Probably not."),
        ("fact", f"Our on-call rotation is {rotation} long, and the database escalation contact is {contact}."),
        ("distractor", f"If I were on the database team, I'd own the {other_service} service too."),
        ("fact", f"The {service} index rebuild window is {window}."),
        ("distractor", "Long day. The coffee machine on our floor is broken again, so that's fun."),
        ("update", f"Update: I moved last month. I live in {city2} now."),
        ("update", f"Correction: since this week my manager is {manager2}."),
        ("update", f"The {service} rebuild window changed: it's {window2} from now on."),
    ]
    facts = {"home city": (f"Ada lives in {city2}.", city), "owned service": (f"Ada owns the {service} service.", None),
             "manager": (f"Ada's manager is {manager2}.", manager), "example language": (f"Ada prefers {language} examples.", None),
             "on-call rotation": (f"The on-call rotation is {rotation} long.", None),
             "escalation contact": (f"The database escalation contact is {contact}.", None),
             "rebuild window": (f"The {service} rebuild window is {window2}.", window)}
    questions = {"home city": "Which city do I live in?", "owned service": "Which service do I own?",
                 "manager": "Who is my manager?", "example language": "Which language do I want examples in?",
                 "on-call rotation": "How long is our on-call rotation?", "escalation contact": "Who is the database escalation contact?",
                 "rebuild window": f"When is the {service} rebuild window?"}
    return {"turns": turns, "facts": facts, "questions": questions, "city": city, "city2": city2, "service": service,
            "distractors": [f"Ada lives in {other_city} or plans to move there.", f"Ada owns the {other_service} service.",
                            "The coffee machine on Ada's floor is broken."],
            "canary_ben": f"ZEPHYR-{r.randint(1000, 9999)}", "canary_sealed": f"ORCHID-{r.randint(1000, 9999)}"}
